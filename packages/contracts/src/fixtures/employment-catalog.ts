const offer = (
  id: string,
  audience: VerticalOffer["audience"],
  kind: VerticalOffer["kind"],
  name: string,
  description: string,
  amountMinor: number,
  sortOrder: number,
  entitlements: Record<string, boolean | number | string | string[]> = {},
): EmploymentCatalog["offers"][number] => ({
  id,
  verticalType: "employment",
  marketCode: MARKET,
  audience,
  kind,
  name,
  description,
  prices: [
    {
      id: `${id}.price.fr.v1`,
      amount: { amountMinor, currency: "EUR" },
      billingPeriod:
        kind === "subscription" || kind === "custom" ? "month" : "once",
      durationDays: kind === "free" ? 30 : kind === "pack" ? 30 : undefined,
      trialDays: kind === "subscription" ? 14 : undefined,
      taxRateBps: amountMinor > 0 ? 2000 : 0,
      isActive: true,
    },
  ],
  entitlements: { ...entitlementDefaults, ...entitlements },
  isActive: true,
  isRecommended: id === "employment.employer.growth",
  sortOrder,
});

