const VERSION_ID = "commercial-fr-v1";
const PUBLISHED_AT = "2026-08-22T00:00:00.000Z";

const scope = (
  audience: MonetizationProduct["audience"] = "all",
  categoryIds: string[] = [],
) => ({
  marketCodes: ["FR"],
  currencies: ["EUR"],
  categoryIds,
  subcategoryIds: [],
  typeIds: [],
  subtypeIds: [],
  audiences: [audience],
  planIds: [],
  customerSegments: [],
  publicationChannels: ["web", "mobile"],
});

const entitlement = (
  key: string,
  label: string,
  value: MonetizationEntitlement["value"],
  unit?: string,
): MonetizationEntitlement => ({ key, label, value, unit });

const product = (input: {
  id: string;
  kind: MonetizationProduct["kind"];
  name: string;
  description: string;
  audience?: MonetizationProduct["audience"];
  categoryIds?: string[];
  amountMinor: number;
  annualAmountMinor?: number;
  taxRateBps?: number;
  durationDays?: number;
  trialDays?: number;
  entitlements?: MonetizationEntitlement[];
  recommended?: boolean;
  status?: MonetizationProduct["status"];
  consumers?: string[];
}): MonetizationProduct => ({
  id: input.id,
  versionId: `${VERSION_ID}:${input.id}`,
  code: input.id,
  kind: input.kind,
  name: input.name,
  description: input.description,
  audience: input.audience || "all",
  scope: scope(input.audience, input.categoryIds),
  prices: [
    {
      id: `${VERSION_ID}:${input.id}:month-or-once`,
      amount: { amountMinor: input.amountMinor, currency: "EUR" },
      billingPeriod: input.kind === "subscription" ? "month" : "once",
      taxRateBps: input.taxRateBps || 0,
      priceIncludesTax: input.taxRateBps === 0,
      durationDays: input.durationDays,
      trialDays: input.trialDays,
    },
    ...(input.annualAmountMinor === undefined
      ? []
      : [
          {
            id: `${VERSION_ID}:${input.id}:year`,
            amount: {
              amountMinor: input.annualAmountMinor,
              currency: "EUR",
            },
            billingPeriod: "year" as const,
            taxRateBps: input.taxRateBps || 0,
            priceIncludesTax: input.taxRateBps === 0,
          },
        ]),
  ],
  entitlements: input.entitlements || [],
  compatibility: {
    requiresProductIds: [],
    excludesProductIds: [],
    maximumQuantity: 1,
  },
  status: input.status || "active",
  recommended: input.recommended || false,
  effectiveFrom: PUBLISHED_AT,
  sourceConsumers: input.consumers || [],
});

