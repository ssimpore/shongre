export async function renderBrandMobileImageRegistry(): Promise<string> {
  const { mobile } = brandConsumerAssets;
  const moduleDirectory = path.dirname(
    absoluteRepositoryPath(brandMobileImageRegistryDestination),
  );
  const requirePath = (destination: string) => {
    assertMappedDestination(destination);
    const relative = path
      .relative(moduleDirectory, absoluteRepositoryPath(destination))
      .replaceAll(path.sep, "/");
    return relative.startsWith(".") ? relative : `./${relative}`;
  };
  return format(
    `/** GENERATED by scripts/sync-brand-assets.ts. Do not edit manually. */\nimport type { ImageSourcePropType } from "react-native";\n\nexport const mobileBrandImages = {\n  primary: require(${JSON.stringify(requirePath(mobile.horizontalPrimary))}),\n  reverse: require(${JSON.stringify(requirePath(mobile.horizontalReverse))}),\n} satisfies Record<"primary" | "reverse", ImageSourcePropType>;\n`,
    { parser: "typescript" },
  );
}

export function absoluteRepositoryPath(relative: string): string {
  const target = path.resolve(repositoryRoot, relative);
  const rootWithSeparator = `${repositoryRoot}${path.sep}`;
  if (!target.startsWith(rootWithSeparator)) {
    throw new Error(`Managed brand path escapes the repository: ${relative}`);
  }
  return target;
}

export function canonicalBrandPath(relative: string): string {
  const target = path.resolve(brandSourceRoot, relative);
  const rootWithSeparator = `${brandSourceRoot}${path.sep}`;
  if (
    path.isAbsolute(relative) ||
    relative.split(/[\\/]/).includes("..") ||
    !target.startsWith(rootWithSeparator)
  ) {
    throw new Error(`Canonical brand path escapes the active kit: ${relative}`);
  }
  return target;
}
