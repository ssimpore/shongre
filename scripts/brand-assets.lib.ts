function assertMappedDestination(
  destination: string,
  options: { directory?: boolean } = {},
): void {
  const matched = brandAssetMappings.some(({ destination: mapped }) =>
    options.directory
      ? mapped.startsWith(`${destination.replace(/\/$/, "")}/`)
      : mapped === destination,
  );
  if (!matched) {
    throw new Error(
      `Brand consumer registry points outside managed mappings: ${destination}`,
    );
  }
}

function webPublicPath(destination: string): string {
  assertMappedDestination(destination);
  const prefix = "frontend/public/";
  if (!destination.startsWith(prefix)) {
    throw new Error(`Web brand asset is not public: ${destination}`);
  }
  return `/${destination.slice(prefix.length)}`;
}

function versionedWebPublicPath(destination: string, version: string): string {
  return `${webPublicPath(destination)}?brand=${version}`;
}

function mobileProjectPath(
  destination: string,
  options: { directory?: boolean } = {},
): string {
  assertMappedDestination(destination, options);
  const prefix = "mobile/";
  if (!destination.startsWith(prefix)) {
    throw new Error(
      `Mobile brand asset is outside the Expo project: ${destination}`,
    );
  }
  return `./${destination.slice(prefix.length)}`;
}

